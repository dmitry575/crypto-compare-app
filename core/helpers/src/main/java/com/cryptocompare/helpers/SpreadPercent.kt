package com.cryptocompare.helpers

/**
 * Спред пары в процентах: сколько получится, если купить на одной бирже
 * и продать на другой.
 *
 * ```
 * (sellPrice - buyPrice) / buyPrice * 100
 * ```
 *
 * [buyPrice] — цена, по которой покупает **пользователь** (лучший ask среди бирж),
 * [sellPrice] — по которой он продаёт (лучший bid). Имена именно от лица
 * пользователя, потому что так же названы поля в best-выдаче бэкенда, и формула
 * повторяет серверный `spreadPercent` дословно: на живых данных они сходятся
 * до последнего знака. Осторожно: в разбивке по биржам
 * (`/v1/symbols/ticker/{ticker}`) те же имена значат обратное — `priceSell` там
 * ask, `priceBuy` — bid. Подробности в решении 6 `CLAUDE.md`.
 *
 * **Знак значим, и в норме он отрицательный:** купить дороже, чем продать, —
 * обычное состояние рынка. По каталогу на 2026-09-08 отрицательны 85% пар,
 * медиана −0.33%. Положительное значение означает реальную возможность
 * заработать на разнице и потому редко.
 *
 * Раньше здесь жили три функции: ширина рынка, арбитраж и bid/ask одной биржи.
 * Первая брала модуль и теряла знак, из-за чего каталог показывал бодрый плюс
 * там, где рынок говорил минус. Отдельная функция для одной биржи не нужна:
 * при единственной бирже [buyPrice] и [sellPrice] — это её собственные ask и
 * bid, и формула вырождается в её спред, тоже со знаком минус.
 *
 * Возвращает `null`, когда считать не из чего: нет цены, она неположительна или
 * не является числом. Ноль в таком случае был бы враньём — «спреда нет» и
 * «спред неизвестен» это разные вещи.
 */
fun spreadPercent(
    buyPrice: Double?,
    sellPrice: Double?,
): Double? {
    if (buyPrice == null || sellPrice == null) return null
    if (buyPrice <= 0.0 || sellPrice <= 0.0) return null
    if (!buyPrice.isFinite() || !sellPrice.isFinite()) return null

    return (sellPrice - buyPrice) * PERCENT_SCALE / buyPrice
}

private const val PERCENT_SCALE = 100.0
