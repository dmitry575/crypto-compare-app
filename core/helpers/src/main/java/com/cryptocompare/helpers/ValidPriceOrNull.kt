package com.cryptocompare.helpers

/**
 * Цена, которой можно верить, или `null`.
 *
 * Биржа, у которой нет одной из сторон стакана, отдаёт на её месте ноль — и
 * в REST, и в сокете. Показанный как есть, он читается как «отдают даром», а в
 * сортировке по цене покупки такая биржа выходит самой дешёвой. `NaN` и
 * бесконечность проходят проверку `> 0` по-разному: первый нет, вторая да,
 * поэтому конечность проверяется отдельно.
 */
fun Double?.validPriceOrNull(): Double? = this?.takeIf { it.isFinite() && it > 0.0 }
