package com.cryptocompare.helpers

/**
 * Тикеры, готовые уйти в подписку: к одному виду, без пустых и не больше [limit].
 *
 * Бэкенд принимает ограниченное число подписок на соединение, а девятая
 * возвращает ошибку без указания тикера — сопоставить её с запросом можно
 * только по порядку ответов. Поэтому лимит применяется до отправки, а не
 * разбирается после.
 *
 * Порядок исходной последовательности сохраняется: обрезаются последние, и
 * экран сам решает, кто у него важнее, поставив их первыми.
 */
fun Iterable<String>.toSubscriptionSet(limit: Int): Set<String> =
    asSequence()
        .map { it.lowercase() }
        .filter { it.isNotBlank() }
        .distinct()
        .take(limit)
        .toSet()
