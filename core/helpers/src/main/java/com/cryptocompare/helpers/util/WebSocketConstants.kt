package com.cryptocompare.helpers.util

/** Коды закрытия и параметры переподключения веб-сокета. */
object WebSocketConstants {
    /** Тег логов потока котировок: `adb logcat -s TickerSocket`. */
    const val LOG_TAG = "TickerSocket"

    /** Сколько символов сырого сообщения писать в лог при ошибке разбора. */
    const val RAW_LOG_LIMIT = 300

    /**
     * Больше бэкенд не принимает: девятая подписка в соединении возвращает
     * `Subscribe failed` (errorCode 2), причём без указания тикера — в отличие
     * от подтверждения, которое тикер называет. Слот освобождается после
     * `unsubscribe`.
     *
     * Проверено на живом сервере 2026-09-08: восемь подписок подтверждаются,
     * девятая падает. В `WebSocketProtocol.md` долго стояло «up to 7»; бэкенд
     * подтвердил восемь и поправил документацию 2026-09-15. Если лимит на
     * сервере поменяют, поменять и здесь.
     */
    const val MAX_SUBSCRIPTIONS = 8

    /**
     * Запас сообщений в потоке событий. Тики идут десятками в секунду, а экран
     * между ними успевает и в базу сходить: без запаса поток либо тормозил бы
     * приём, либо ронял свежие сообщения. Переполнение выбрасывает самые
     * старые — цена минутной давности не нужна никому.
     */
    const val EVENT_BUFFER_CAPACITY = 256

    /**
     * Сколько поток должен пролежать, чтобы экран сказал «цены не обновляются».
     * Короткий разрыв чинится сам за секунду-другую, и полоска на нём только
     * мигала бы. Одна на каталог и портфель: иначе один экран уже говорил бы о
     * замерших ценах, а другой ещё нет.
     */
    const val STALE_NOTICE_DELAY_MS = 4_000L

    const val NORMAL_CLOSURE_STATUS = 1000
    const val BASE_RECONNECT_DELAY_MS = 1_000L
    const val MAX_RECONNECT_DELAY_MS = 30_000L
    const val RECONNECT_JITTER_MS = 500L

    /**
     * Сколько соединение должно продержаться, чтобы бэкофф начался заново с
     * [BASE_RECONNECT_DELAY_MS]. Короче — сервер, рвущий соединение сразу после
     * открытия, получал бы реконнект раз в секунду.
     */
    const val STABLE_CONNECTION_MS = 10_000L
    const val MAX_EXPONENT = 5
    const val UNKNOWN_ERROR_CODE = -1
}
