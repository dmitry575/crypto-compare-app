package com.cryptocompare.helpers.util

/** Параметры загрузки каталога и истории цен. */
object CryptoCompareRepositoryConstants {
    const val CATALOG_CACHE_TTL_MILLIS = 24 * 60 * 60 * 1000L

    /**
     * Размер страницы каталога. Бэкенд принимает 1..500; берём максимум —
     * каталог из ~3700 пар это восемь запросов вместо ста пятидесяти.
     */
    const val SYMBOLS_IN_ROW = 500

    /**
     * Страница справочника бирж. Их 31, но параметр обязателен: без него
     * эндпоинт отдаёт десять штук по умолчанию, и приложение знало ровно
     * десять бирж из тридцати одной — остальные молча выпадали с детального
     * экрана, потому что для них не находился провайдер.
     */
    const val PROVIDERS_IN_ROW = 500
}
