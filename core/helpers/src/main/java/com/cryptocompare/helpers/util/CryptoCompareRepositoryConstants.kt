package com.cryptocompare.helpers.util

/** Параметры загрузки каталога и истории цен. */
object CryptoCompareRepositoryConstants {
    const val CATALOG_CACHE_TTL_MILLIS = 24 * 60 * 60 * 1000L

    /**
     * Размер страницы каталога. Бэкенд принимает 1..500; берём максимум —
     * каталог из ~3700 пар это восемь запросов вместо ста пятидесяти.
     */
    const val SYMBOLS_IN_ROW = 500

    /**
     * Порядок, в котором каталог выкачивается страницами.
     *
     * По умолчанию бэкенд отдаёт `updatedAt desc` — самый подвижный ключ из всех:
     * пока идёт выкачка, котировки обновляются, строки переезжают между
     * страницами, и часть символов приезжает дважды, а часть не приезжает вовсе.
     * Полная синхронизация ещё и удаляет всё, чего не встретила, — то есть
     * пропущенный символ исчезал из каталога до следующего раза.
     *
     * Тикер от котировок не зависит. Символы одного тикера (разные сети) между
     * собой бэкенд пока может переставлять — вторичный ключ по `id` заведён у
     * него задачей Crypto.Compare#52.
     */
    const val CATALOG_SORT_BY = "ticker"
    const val CATALOG_SORT_DIR = "asc"

    /**
     * Страница справочника бирж. Их 31, но параметр обязателен: без него
     * эндпоинт отдаёт десять штук по умолчанию, и приложение знало ровно
     * десять бирж из тридцати одной — остальные молча выпадали с детального
     * экрана, потому что для них не находился провайдер.
     */
    const val PROVIDERS_IN_ROW = 500
}
