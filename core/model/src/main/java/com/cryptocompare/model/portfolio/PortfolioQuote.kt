package com.cryptocompare.model.portfolio

/**
 * Последняя цена продажи (bid) символа на бирже, за которой закреплена позиция.
 *
 * В каталоге лежит только лучшая пара по символу, котировки отдельных бирж
 * приходят лишь из сети. Без своей копии позиция с биржей при запуске без сети
 * осталась бы без цены, поэтому последнюю котировку храним на устройстве.
 */
data class PortfolioQuote(
    val symbolId: Long,
    val providerId: Int,
    val price: Double,
    /** Когда биржа отдала котировку, в миллисекундах эпохи. */
    val quotedAtMillis: Long,
)
