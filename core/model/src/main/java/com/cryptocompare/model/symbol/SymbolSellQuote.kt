package com.cryptocompare.model.symbol

/**
 * Цена, по которой символ можно продать прямо сейчас, и биржа, которая её даёт.
 *
 * Это лучший bid среди бирж символа — сторона, по которой закрывают позицию.
 * Биржа меняется вместе с рынком: сегодня лучший bid на bitget, завтра на htx,
 * и без её имени стоимость позиции прыгала бы без объяснения.
 */
data class SymbolSellQuote(
    val price: Double,
    /** Биржа с лучшим bid; `null` — бэкенд её не назвал. */
    val providerId: Int?,
    /** Имя этой биржи из справочника; `null` — её там ещё нет. */
    val exchangeName: String?,
)
