package com.cryptocompare.model.portfolio

/**
 * Позиция вместе с тем, сколько она стоит сейчас.
 *
 * Текущая цена — **цена продажи** символа: bid биржи, где куплена монета, а
 * если биржа не указана — лучший bid среди всех бирж. Позицию закрывают
 * продажей, и считать прибыль по цене покупки значило бы обещать пользователю
 * деньги, которых он за актив не получит.
 *
 * Все денежные поля, кроме [invested], обнуляются в `null`, а не в ноль, когда
 * цены нет: ноль читается как «позиция обесценилась», а это другое.
 */
data class PortfolioHolding(
    val position: PortfolioPosition,
    /** Цена продажи; `null` — цены нет. */
    val currentPrice: Double?,
    /**
     * Биржа, чья это цена. Лучший bid переезжает с площадки на площадку, и
     * без её имени непонятно, почему позиция вдруг подешевела. У позиции с
     * указанной биржей — всегда она, даже пока цены нет. `null` — цены нет у
     * позиции без биржи или биржи ещё нет в справочнике.
     */
    val priceExchange: String? = null,
    /** Вложено: количество × средняя цена покупки. Считается без цены рынка. */
    val invested: Double,
    /** Стоимость сейчас: количество × [currentPrice]. */
    val currentValue: Double?,
    /** Прибыль в котируемой валюте: [currentValue] − [invested]. */
    val profit: Double?,
    /** Прибыль в процентах от вложенного; `null` ещё и когда вложено ноль. */
    val profitPercent: Double?,
)
