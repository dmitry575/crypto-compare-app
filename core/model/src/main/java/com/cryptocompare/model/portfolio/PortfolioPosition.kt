package com.cryptocompare.model.portfolio

/**
 * Позиция в портфеле: сколько актива куплено, по какой средней цене и где.
 *
 * Ключ — символ, а не тикер: USDC в Ethereum и USDC в Solana это разные активы
 * (решение 1 в `CLAUDE.md`), и складывать их в одну строку значило бы считать
 * прибыль по цене чужой сети. Позиция на символ одна: повторная покупка меняет
 * количество и среднюю цену, а не заводит второй лот.
 *
 * [ticker] лежит рядом денормализованным — им позиция называется, когда символа
 * в каталоге уже нет.
 */
data class PortfolioPosition(
    val symbolId: Long,
    val ticker: String,
    /** Количество базового актива: 0.42 BTC. */
    val amount: Double,
    /** Средняя цена покупки в котируемой валюте. */
    val buyPrice: Double,
    val updatedAtMillis: Long,
    /**
     * Биржа, где куплена монета: позиция оценивается по её bid, потому что
     * продать монету можно только там, где она лежит. `null` — биржа не указана,
     * и позиция оценивается лучшим bid среди всех бирж, как до этого поля.
     */
    val providerId: Int? = null,
    /** Имя этой биржи из справочника; `null` — биржа не указана или её там ещё нет. */
    val exchangeName: String? = null,
)
