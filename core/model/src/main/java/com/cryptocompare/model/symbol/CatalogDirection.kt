package com.cryptocompare.model.symbol

/**
 * Фильтр каталога по направлению цены за 24 часа.
 *
 * Отдельно от фильтра избранного, а не одним списком из четырёх вариантов:
 * «избранное, которое сегодня растёт» — это ровно тот вопрос, ради которого
 * избранное и заводят, и одним выбором его не задать.
 */
enum class CatalogDirection {
    /** Без ограничения по направлению. */
    ANY,

    /** Только пары, выросшие за сутки. */
    GAINERS,

    /** Только пары, упавшие за сутки. */
    LOSERS,
}
