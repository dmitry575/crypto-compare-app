package com.cryptocompare.model.symbol

/**
 * Строка каталога: один символ — пара в одном наборе сетей — с лучшей парой цен
 * по его биржам.
 *
 * Раньше строка была одна на тикер и сводила все символы: USDC в Ethereum и
 * USDC в Solana попадали в одну строку. Теперь каждый символ отдельно и
 * помечен сетями.
 */
data class PairAggregateRow(
    val symbolId: Long,
    val ticker: String,
    /** `eth/usdc`: из него берётся базовый актив для разбора сетей. */
    val symbol: String?,
    /** Цена, по которой покупает пользователь: лучший ask среди бирж символа. */
    val buyPrice: Double,
    /** Цена, по которой продаёт пользователь: лучший bid среди бирж символа. */
    val sellPrice: Double,
    /**
     * Спред в процентах от цены покупки, со знаком. Приходит с бэкенда готовым,
     * приложение его не пересчитывает. `null` — считать не из чего.
     */
    val spreadPercent: Double?,
    /**
     * Объём символа за 24ч в котируемом активе. Именно котируемый: сравнить
     * «1.25M BTC» и «800B SHIB» в соседних строках нельзя, а в USDT обе строки
     * сравнимы. Ноль приходит как `null` — это «биржа не отдала статистику».
     */
    val quoteVolume24h: Double? = null,
    val change24h: Double? = null,
    /** Сети символа строкой в формате источника. */
    val network: String? = null,
    /** Сколько символов у этого тикера в каталоге; больше одного — строку надо пометить сетями. */
    val networkCount: Int = 1,
)
