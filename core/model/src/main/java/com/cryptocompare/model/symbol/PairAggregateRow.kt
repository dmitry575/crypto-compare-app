package com.cryptocompare.model.symbol

/** Строка агрегата каталога: одна пара, свёрнутая по всем биржам. */
data class PairAggregateRow(
    val ticker: String,
    val symbolIds: String?,
    val providerIds: String?,
    val minPrice: Double,
    val maxPrice: Double,
    /** Разброс между биржами в процентах от минимальной цены. Считается в SQL. */
    val spreadPercent: Double,
    /**
     * Суммарный объём пары за 24ч в котируемом активе по всем биржам.
     *
     * Именно котируемый, а не базовый: сложить BTC одной биржи с BTC другой
     * ещё можно, но сравнить получившиеся «1.25M BTC» и «800B SHIB» в соседних
     * строках списка — уже нет. В котируемом активе обе строки в USDT.
     */
    val quoteVolume24h: Double? = null,
    /**
     * Изменение цены за 24ч, наибольшее по модулю среди бирж (знак сохраняется).
     *
     * Не среднее: биржа с протухшими или нулевыми котировками весила бы в AVG
     * столько же, сколько основной рынок, и гасила бы реальное движение.
     */
    val change24h: Double? = null,
)
